// Each purchased tier contributes its own permanent bonuses.
const stations = ([
  ['I', 3, 0, 0],
  ['II', 0, 2, 0],
  ['III', 3, 0, 2],
  ['IV', 0, 3, 0],
  ['V', 3, 0, 0],
  ['VI', 0, 2, 3],
  ['VII', 3, 0, 0],
  ['VIII', 3, 5, 3],
] as const).map(([tier, stepSkipping, doubling, preservation]) => ({
  id: `BeastcraftingStation${tier}`, name: `Beastcrafting Station ${tier}`, stepSkipping, doubling, preservation,
}));

export function resolveBeastcraftingStations(save: Pick<DecodedSave, 'version' | 'demo' | 'shopPurchases'> | null) {
  const purchases = save?.version === 32 && !save.demo ? save.shopPurchases : null;
  const purchased = stations.filter(({ id }) => (purchases?.[`MelvorBase:${id}`] ?? 0) > 0);
  return {
    purchased,
    stepSkipping: purchased.reduce((total, station) => total + station.stepSkipping, 0),
    doubling: purchased.reduce((total, station) => total + station.doubling, 0),
    preservation: purchased.reduce((total, station) => total + station.preservation, 0),
  };
}
