export const combatEnemies = enemyRows.map(([id, name, enemyHealth, baseArmour = 0, baseWard = 0]) => ({
  id, name, enemyHealth, baseArmour, baseWard,
})).sort((a, b) => a.name.localeCompare(b.name));

const enemiesById = new Map(combatEnemies.map((enemy) => [enemy.id, enemy]));

export const combatAreas = [
  ...areaRows.map(([id, name, category, enemies]) => ({ id, name, category, enemies, isDungeon: false as const })),
  ...dungeonRows.map(([id, name, category, lineup, rewards]) => ({
    id, name, category, isDungeon: true as const,
    enemies: lineup.map(([enemyId]) => enemyId),
    lineup: lineup.map(([enemyId, count]) => {
      const enemy = enemiesById.get(enemyId);
      if (!enemy) throw new Error(`Unknown enemy ${enemyId} in ${name}.`);
      return { ...enemy, count };
    }),
    rewards: rewards.map(([name, min, max = min]) => ({ name, min, max })),
  })),
];

export const combatAreaCategories = [...new Set(combatAreas.map(({ category }) => category))];
